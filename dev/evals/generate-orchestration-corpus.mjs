for (const [index, prompt] of directTaskPrompts.entries()) {
  cases.push({
    id: `orch-dt-${String(index + 1).padStart(2, "0")}`,
    caseClass: "direct_task",
    prompt,
    allowedTools: writeExecutionTools,
    sources: frozenCrossLayerSources,
    manifestFileOrder: frozenCrossLayerOrder,
    assertions: [
      {
        kind: "file_unchanged",
        path: "tests/acceptance.rs",
      },
    ],
    // Exercise the public behavior instead of pinning one valid lowercase implementation.
    // The committed acceptance test distinguishes parser normalization and formatter rendering,
    // while file_unchanged prevents an agent from weakening that oracle.
    checkCommand: ["cargo", "test", "--quiet"],
  });
}

for (const [index, prompt] of planReviewPrompts.entries()) {
  cases.push({
    id: `orch-pr-${String(index + 1).padStart(2, "0")}`,
    caseClass: "plan_review",
    prompt,
    allowedTools: readDiscoveryTools,
    sources: frozenCrossLayerSources,
    manifestFileOrder: frozenCrossLayerOrder,
    assertions: [{ kind: "workspace_source_unchanged" }],
  });
}

const count = (caseClass) =>
  cases.filter((item) => item.caseClass === caseClass).length;
if (count("chat") !== 20 || count("plan_review") !== 15 || count("direct_task") !== 15) {
  throw new Error(
    "orchestration corpus must contain exactly 20 chat, 15 plan_review, and 15 direct_task cases",
  );
}

const expectedFiles = new Map();

for (const item of cases) {
  const files = item.sources["Cargo.toml"]
    ? { ...item.sources }
    : {
        "Cargo.toml": cargoToml(item.id),
        "Cargo.lock": cargoLock(item.id),
        ...item.sources,
      };
  const prompt = `${item.prompt}\n`;
  const manifest = [
    "schema_version = 1",
    `id = ${JSON.stringify(item.id)}`,
    'prompt_file = "prompt.txt"',
    `prompt_sha256 = ${JSON.stringify(sha256(prompt))}`,
    `allowed_tools = [${item.allowedTools.map((value) => JSON.stringify(value)).join(", ")}]`,
    "max_turns = 16",
    "max_output_tokens = 16384",
    'expected_terminal = ["completed"]',
    'expected_verification = ["passed"]',
    "",
    "[orchestration]",
    `case_class = ${JSON.stringify(item.caseClass)}`,
    'corpus_version = "rfc-0063-orchestration-v1"',
    "",
  ];

  item.assertions.forEach((assertion, assertionIndex) => {
    manifest.push("[[assertions]]");
    manifest.push(`id = "acceptance-${assertionIndex + 1}"`);
    manifest.push(`kind = ${JSON.stringify(assertion.kind)}`);
    if (assertion.path) {
      manifest.push(`path = ${JSON.stringify(assertion.path)}`);
    }
    if (assertion.text) {
      manifest.push(`text = ${JSON.stringify(assertion.text)}`);
    }
    manifest.push("");
  });

  const fileEntries = item.manifestFileOrder
    ? item.manifestFileOrder.map((path) => [path, files[path]])
    : Object.entries(files).sort(([left], [right]) => left.localeCompare(right));
  fileEntries.forEach(([path, content]) => {
    manifest.push("[[files]]");
    manifest.push(`path = ${JSON.stringify(path)}`);
    manifest.push(`source = ${JSON.stringify(`files/${path}`)}`);
    manifest.push(`sha256 = ${JSON.stringify(sha256(content))}`);
    manifest.push("");
  });

  const checkCommand = item.checkCommand ?? ["cargo", "check", "--quiet"];
  manifest.push("[[checks]]");
  manifest.push(
    `id = ${JSON.stringify(checkCommand[1] === "test" ? "cargo-test" : "cargo-check")}`,
  );
  manifest.push(
    `command = [${checkCommand.map((value) => JSON.stringify(value)).join(", ")}]`,
  );
  manifest.push("timeout_ms = 30000");
  manifest.push("");

  const fixtureRoot = `${item.caseClass === "chat" ? "negative" : "positive"}/${item.id}`;
  expectedFiles.set(`${fixtureRoot}/prompt.txt`, prompt);
  expectedFiles.set(`${fixtureRoot}/fixture.toml`, `${manifest.join("\n")}`);
  for (const [path, content] of Object.entries(files)) {
    expectedFiles.set(`${fixtureRoot}/files/${path}`, content);
  }
}

const actualFiles = (root) => {
  const files = [];
  const walk = (directory) => {
    for (const name of readdirSync(directory)) {
      const path = resolve(directory, name);
      if (statSync(path).isDirectory()) {
        walk(path);
      } else {
        files.push(relative(root, path));
      }
    }
  };
  walk(root);
  return files.sort();
};

if (mode === "--write") {
  rmSync(outputRoot, { recursive: true, force: true });
  for (const [path, content] of expectedFiles) {
    const absolute = resolve(outputRoot, path);
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, content);
  }
} else {
  const expectedPaths = [...expectedFiles.keys()].sort();
  const observedPaths = actualFiles(outputRoot);
  if (JSON.stringify(expectedPaths) !== JSON.stringify(observedPaths)) {
    throw new Error("generated orchestration corpus file list is stale");
  }
  for (const [path, expected] of expectedFiles) {
    const observed = readFileSync(resolve(outputRoot, path), "utf8");
    if (observed !== expected) {
      throw new Error(`generated orchestration corpus is stale: ${path}`);
    }
  }
}
