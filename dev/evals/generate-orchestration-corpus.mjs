#!/usr/bin/env node

import { createHash } from "node:crypto";
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDir, "../..");
const outputRoot = resolve(
  repositoryRoot,
  "dev/evals/model-fixtures/orchestration-v1",
);
const mode = process.argv[2] ?? "--check";

if (!["--check", "--write"].includes(mode)) {
  throw new Error("usage: generate-orchestration-corpus.mjs [--check|--write]");
}

const sha256 = (value) =>
  `sha256:${createHash("sha256").update(value).digest("hex")}`;

const cargoToml = (id) => `[package]
name = "sigil-eval-${id}"
version = "0.1.0"
edition = "2024"

[lib]
path = "src/lib.rs"

[workspace]
`;

const cargoLock = (id) => `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "sigil-eval-${id}"
version = "0.1.0"
`;

const unchangedSources = {
  "src/lib.rs": `pub mod formatter;
pub mod parser;

pub fn render_record(input: &str) -> String {
    formatter::render(&parser::parse(input))
}
`,
  "src/parser.rs": `pub fn parse(input: &str) -> String {
    input.trim().to_owned()
}
`,
  "src/formatter.rs": `pub fn render(value: &str) -> String {
    format!("record:{value}")
}
`,
};

const questionPrompts = [
  "Explain how render_record transforms its input. Do not modify any files.",
  "Which module removes surrounding whitespace, and how is it called? Do not edit the workspace.",
  "Describe the output produced by render_record for the input `  alpha  `. Do not change code.",
  "Explain the responsibility boundary between parser and formatter. Make no file changes.",
  "Review the three source files and summarize the call flow. Do not modify the repository.",
  "What string prefix is added by the formatter, and where is that behavior defined? Do not edit.",
  "Explain whether parse borrows or owns its returned value. Keep the workspace unchanged.",
];

const symbolPrompts = [
  "Locate the definition of render_record and name the functions it calls. Do not modify files.",
  "Find the parse symbol and report its input and return types. Do not edit the workspace.",
  "Find every reference to formatter::render and summarize it. Make no changes.",
  "Identify which public modules are exported by src/lib.rs. Do not modify code.",
  "Locate the literal `record:` and explain how it reaches the public API. Do not edit.",
  "Find the function that calls input.trim() and report its module path. Keep files unchanged.",
  "Locate all functions returning String and list their module-qualified names. Do not modify files.",
];

const positiveResearchPrompts = [
  "Investigate parser and formatter independently, compare their ownership and allocation behavior, and return a consolidated design review. Use parallel exploration where useful; do not modify files.",
  "Perform a parallel review of the public facade, parser, and formatter. Report coupling risks and a proposed refactor sequence without changing the workspace.",
  "Analyze the parser and formatter as independent workstreams, then synthesize how errors and normalization should be introduced across the pipeline. Do not edit files.",
];

const cases = [];

for (const [index, prompt] of questionPrompts.entries()) {
  cases.push({
    id: `orch-neg-question-${String(index + 1).padStart(2, "0")}`,
    caseClass: "negative",
    prompt,
    allowedTools: ["read_file"],
    sources: unchangedSources,
    assertions: [{ kind: "workspace_source_unchanged" }],
  });
}

for (const [index, prompt] of symbolPrompts.entries()) {
  cases.push({
    id: `orch-neg-symbol-${String(index + 1).padStart(2, "0")}`,
    caseClass: "negative",
    prompt,
    allowedTools: ["read_file"],
    sources: unchangedSources,
    assertions: [{ kind: "workspace_source_unchanged" }],
  });
}

for (let index = 1; index <= 6; index += 1) {
  const value = index + 2;
  cases.push({
    id: `orch-neg-single-edit-${String(index).padStart(2, "0")}`,
    caseClass: "negative",
    prompt: `Change only retry_limit in src/lib.rs so it returns ${value}. Keep this as one direct, minimal edit.`,
    allowedTools: ["read_file", "edit_file"],
    sources: {
      "src/lib.rs": `pub fn retry_limit() -> u32 {
    1
}
`,
    },
    assertions: [
      {
        kind: "file_contains",
        path: "src/lib.rs",
        text: `    ${value}`,
      },
    ],
  });
}

for (let index = 1; index <= 4; index += 1) {
  cases.push({
    id: `orch-pos-cross-layer-${String(index).padStart(2, "0")}`,
    caseClass: "positive",
    prompt:
      "Implement the normalization change across the parser and formatter: lowercase parsed values, then wrap rendered values in square brackets. Coordinate the cross-module work and keep the public facade compiling.",
    allowedTools: ["read_file", "edit_file"],
    sources: unchangedSources,
    assertions: [
      {
        kind: "file_contains",
        path: "src/parser.rs",
        text: ".to_ascii_lowercase()",
      },
      {
        kind: "file_contains",
        path: "src/formatter.rs",
        text: 'format!("[{value}]")',
      },
    ],
  });
}

for (const [index, prompt] of positiveResearchPrompts.entries()) {
  cases.push({
    id: `orch-pos-parallel-research-${String(index + 1).padStart(2, "0")}`,
    caseClass: "positive",
    prompt,
    allowedTools: ["read_file"],
    sources: unchangedSources,
    assertions: [{ kind: "workspace_source_unchanged" }],
  });
}

for (let index = 1; index <= 3; index += 1) {
  const quota = index + 3;
  const timeout = index + 7;
  cases.push({
    id: `orch-pos-independent-modules-${String(index).padStart(2, "0")}`,
    caseClass: "positive",
    prompt: `Implement two independent configuration changes and coordinate them as separate workstreams: set quota::default_quota to ${quota} and timeout::default_timeout to ${timeout}. Keep the facade compiling.`,
    allowedTools: ["read_file", "edit_file"],
    sources: {
      "src/lib.rs": `pub mod quota;
pub mod timeout;

pub fn defaults() -> (u32, u32) {
    (quota::default_quota(), timeout::default_timeout())
}
`,
      "src/quota.rs": `pub fn default_quota() -> u32 {
    1
}
`,
      "src/timeout.rs": `pub fn default_timeout() -> u32 {
    1
}
`,
    },
    assertions: [
      {
        kind: "file_contains",
        path: "src/quota.rs",
        text: `    ${quota}`,
      },
      {
        kind: "file_contains",
        path: "src/timeout.rs",
        text: `    ${timeout}`,
      },
    ],
  });
}

if (
  cases.filter((item) => item.caseClass === "negative").length !== 20 ||
  cases.filter((item) => item.caseClass === "positive").length !== 10
) {
  throw new Error("orchestration corpus must contain exactly 20 negative and 10 positive cases");
}

const expectedFiles = new Map();

for (const item of cases) {
  const files = {
    "Cargo.toml": cargoToml(item.id),
    "Cargo.lock": cargoLock(item.id),
    ...item.sources,
  };
  const prompt = `${item.prompt}\n`;
  const manifest = [
    "schema_version = 1",
    `id = ${JSON.stringify(item.id)}`,
    'prompt_file = "prompt.txt"',
    `prompt_sha256 = ${JSON.stringify(sha256(prompt))}`,
    `allowed_tools = [${item.allowedTools.map((value) => JSON.stringify(value)).join(", ")}]`,
    "max_turns = 16",
    "max_output_tokens = 16384",
    'expected_terminal = ["completed"]',
    'expected_verification = ["passed"]',
    "",
    "[orchestration]",
    `case_class = ${JSON.stringify(item.caseClass)}`,
    'corpus_version = "rfc-0053-orchestration-v1"',
    "",
  ];

  item.assertions.forEach((assertion, assertionIndex) => {
    manifest.push("[[assertions]]");
    manifest.push(`id = "acceptance-${assertionIndex + 1}"`);
    manifest.push(`kind = ${JSON.stringify(assertion.kind)}`);
    if (assertion.path) {
      manifest.push(`path = ${JSON.stringify(assertion.path)}`);
    }
    if (assertion.text) {
      manifest.push(`text = ${JSON.stringify(assertion.text)}`);
    }
    manifest.push("");
  });

  Object.entries(files)
    .sort(([left], [right]) => left.localeCompare(right))
    .forEach(([path, content]) => {
      manifest.push("[[files]]");
      manifest.push(`path = ${JSON.stringify(path)}`);
      manifest.push(`source = ${JSON.stringify(`files/${path}`)}`);
      manifest.push(`sha256 = ${JSON.stringify(sha256(content))}`);
      manifest.push("");
    });

  manifest.push("[[checks]]");
  manifest.push('id = "cargo-check"');
  manifest.push('command = ["cargo", "check", "--quiet"]');
  manifest.push("timeout_ms = 30000");
  manifest.push("");

  const fixtureRoot = `${item.caseClass}/${item.id}`;
  expectedFiles.set(`${fixtureRoot}/prompt.txt`, prompt);
  expectedFiles.set(`${fixtureRoot}/fixture.toml`, `${manifest.join("\n")}`);
  for (const [path, content] of Object.entries(files)) {
    expectedFiles.set(`${fixtureRoot}/files/${path}`, content);
  }
}

const actualFiles = (root) => {
  const files = [];
  const walk = (directory) => {
    for (const name of readdirSync(directory)) {
      const path = resolve(directory, name);
      if (statSync(path).isDirectory()) {
        walk(path);
      } else {
        files.push(relative(root, path));
      }
    }
  };
  walk(root);
  return files.sort();
};

if (mode === "--write") {
  rmSync(outputRoot, { recursive: true, force: true });
  for (const [path, content] of expectedFiles) {
    const absolute = resolve(outputRoot, path);
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, content);
  }
} else {
  const expectedPaths = [...expectedFiles.keys()].sort();
  const observedPaths = actualFiles(outputRoot);
  if (JSON.stringify(expectedPaths) !== JSON.stringify(observedPaths)) {
    throw new Error("generated orchestration corpus file list is stale");
  }
  for (const [path, expected] of expectedFiles) {
    const observed = readFileSync(resolve(outputRoot, path), "utf8");
    if (observed !== expected) {
      throw new Error(`generated orchestration corpus is stale: ${path}`);
    }
  }
}
