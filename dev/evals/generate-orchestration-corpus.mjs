#!/usr/bin/env node

import { createHash } from "node:crypto";
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDir, "../..");
const outputRoot = resolve(
  repositoryRoot,
  "dev/evals/model-fixtures/orchestration-v1",
);
const mode = process.argv[2] ?? "--check";

if (!["--check", "--write"].includes(mode)) {
  throw new Error("usage: generate-orchestration-corpus.mjs [--check|--write]");
}

const sha256 = (value) =>
  `sha256:${createHash("sha256").update(value).digest("hex")}`;

const cargoToml = (id) => `[package]
name = "sigil-eval-${id}"
version = "0.1.0"
edition = "2024"

[lib]
path = "src/lib.rs"

[workspace]
`;

const cargoLock = (id) => `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "sigil-eval-${id}"
version = "0.1.0"
`;

const unchangedSources = {
  "src/lib.rs": `pub mod formatter;
pub mod parser;

pub fn render_record(input: &str) -> String {
    formatter::render(&parser::parse(input))
}
`,
  "src/parser.rs": `pub fn parse(input: &str) -> String {
    input.trim().to_owned()
}
`,
  "src/formatter.rs": `pub fn render(value: &str) -> String {
    format!("record:{value}")
}
`,
};

const crossLayerAcceptanceTest = (id) => `use sigil_eval_${id.replaceAll("-", "_")}::render_record;

#[test]
fn normalizes_then_wraps_the_public_result() {
    assert_eq!(render_record("  MiXeD-42  "), "[mixed-42]");
}
`;

